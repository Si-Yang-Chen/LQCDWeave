"""Joint light-I0/I1, D and charmonium campaign definitions, without submission.

Light I0 and charmonium are separate; charm annihilation is excluded.
All r labels and the complete radial space are retained. Same-flavor radial
pairs are C eigencombinations. Connected and disconnected terms are
generated by the public physical-operator interface.
"""
from __future__ import annotations

from itertools import product
import sympy as sp

from d_meson_spd_r_magnetic_inventory import inventory
from lqcdweave.contraction.binding.api import RecipeVertex
from lqcdweave.operators.correlator.api import (
    Flavor, Hadron, Tag, gen_correlator, remove_disconneted_diagram,
)


LIGHT_EDGES=(0,16,32,48,70)
CHARM_EDGES=(0,16,32,48,70,120)


def mode_bins(edges):
    return tuple(tuple(range(a,b)) for a,b in zip(edges,edges[1:]))


def elemental_reader(dataset):
    """Bind the confirmed orthonormal V/V, empty-path zero-momentum identity.

    This task's scientific declaration does not modify the published dataset.
    Nonlocal and nonzero-momentum kernels retain their stored structures.
    """
    from lqcdweave.adapters.meson_dataset import DatasetElemental
    from lqcdweave.operators.single_hadron.api import meson55_preset
    table = meson55_preset(version='v2')
    declarations = {('v2v', row['component'], mi): 'diagonal'
        for row in table if all(not term['path'] for term in row['terms'])
        for mi, momentum in enumerate(dataset.spec.coordinates('momentum'))
        if tuple(momentum) == (0, 0, 0)}
    return DatasetElemental(dataset, catalog=table, elemental_structures=declarations)


def channels():
    grouped={}
    for part in inventory()['partitions']:
        name=part['name'].rsplit('_r',1)[0]
        channel=grouped.setdefault(name,dict(name=name,momentum=part['momentum'],
            irrep=part['irrep'],parity=part['parity'],rows=part['rows'],operators=[]))
        channel['operators'].extend(part['operators'])
    return tuple(c for c in grouped.values() if c['operators'])


def periodic_pairs(physical_times, *, physical_lt=128, max_dt=32):
    """Ordered cyclic-slot pairs, checked against actual physical differences."""
    times=tuple(physical_times)
    if len(times)!=40 or len(set(times))!=40:
        raise ValueError('this campaign requires the actual forty distinct time slots')
    if {(times[(s+10)%40]-times[s])%physical_lt for s in range(40)}!={32}:
        raise ValueError('actual slot step ten does not correspond to physical dt32')
    pairs=[dict(sink=(s+step)%40,source=s) for s in range(40) for step in range(1,11)]
    expected={(s,t) for s in range(40) for t in range(40)
              if 1 <= (times[t]-times[s])%physical_lt <= max_dt}
    if {(p['source'],p['sink']) for p in pairs}!=expected:
        raise ValueError('cyclic slot pairs differ from the requested physical dt range')
    return pairs


def build_task(selected=None, *, light_bins=None, charm_bins=None, structured=True, elemental=None):
    from lqcdweave.operators.single_hadron.api import momDict_meson55
    selected=channels() if selected is None else selected
    light_bins=mode_bins(LIGHT_EDGES) if light_bins is None else tuple(light_bins)
    charm_bins=mode_bins(CHARM_EDGES) if charm_bins is None else tuple(charm_bins)
    radials=dict(light=tuple(product(light_bins,repeat=2)),
                 charm=tuple(product(charm_bins,repeat=2)),D=tuple(product(light_bins,charm_bins)))
    tags={}; radial_tags={}
    for kind,pairs in radials.items():
        for index,pair in enumerate(pairs):
            tag=len(tags); tags[tag]=pair; radial_tags[kind,index]=tag
    mesons=RecipeVertex(elemental,momentum_dict=momDict_meson55,version='v2')
    flavors=dict(I0=(Flavor('uu')+Flavor('dd'))/sp.sqrt(2),
                 I1=(Flavor('uu')-Flavor('dd'))/sp.sqrt(2),charm=Flavor('cc'),D=Flavor('uc'))
    groups={f'{group}_C{sign}':(kinds,c) for group,kinds in (
        ('I0_light',(('I0','light'),)),('I1_light',(('I1','light'),)),
        ('charmonium',(('charm','charm'),)))
        for sign,c in (('p',1),('m',-1))}
    groups['D']=((('D','D'),),None)
    requests={group:{} for group in groups}; fields={}
    for channel in selected:
        for row in range(channel['rows']):
            for group,(kinds,c_parity) in groups.items():
                basis=[]; records=[]
                for flavor,kind in kinds:
                    for op in channel['operators']:
                        bins=light_bins if kind=='light' else charm_bins
                        choices=(tuple((i,None,((i,sp.Integer(1)),)) for i in range(len(radials[kind])))
                            if kind=='D' else c_radials(len(bins),op['c_label'],c_parity))
                        for radial,exchange,components in choices:
                            terms=[];position=sp.Integer(0)
                            for ordered,coefficient in components:
                                tag=radial_tags[kind,ordered]
                                symbol=mesons.symbol(op['name'],channel['momentum'],irrep=channel['irrep'],
                                    copy_index=op['copy_index'],tag=Tag(tag,'sink'))[row]
                                if elemental is not None and mesons(symbol).with_mode_indices(
                                        radials[kind][ordered]).is_structurally_zero():
                                    continue
                                position+=coefficient*symbol
                                terms.append(dict(tag=tag,coefficient=coefficient,
                                    mode_indices=radials[kind][ordered]))
                            if not terms:
                                continue
                            basis.append(Hadron(position,flavors[flavor]))
                            records.append(dict(flavor=flavor,kind=kind,operator=op,radial=radial,
                                c_parity=c_parity,radial_exchange=exchange,terms=terms))
                if not basis:
                    continue
                full=gen_correlator([list(basis),list(basis)],['sink','source'],
                    [False,True],degenerate=True,structured=structured)
                if group.startswith('charmonium'):
                    full=remove_disconneted_diagram(full,[r'S^c_\mathrm{local}'])
                values={'two_point':full}
                if group=='I0_light_Cp' and channel['name']=='p2_0_A1_Pp':
                    # Select the loops themselves, rather than subtracting
                    # rounded full/connected numerical matrices after replay.
                    values['disconnected']=remove_disconneted_diagram(full,[r'S^q'])
                    for role,dagger in (('sink',False),('source',True)):
                        values[f'vacuum_{role}']=gen_correlator([list(basis)],[role],[dagger],
                            degenerate=True,structured=structured)
                requests[group].setdefault(channel['name'],{})[f'row_{row}']=values
                fields[(group,channel['name'],f'row_{row}')]=dict(channel=channel,row=row,operators=records)
    return {k:v for k,v in requests.items() if v},fields,tags


def c_radials(count,c_factor,c_parity):
    """Full ordered space in C eigenvectors: C O_ab = c_factor O_ba."""
    exchange=c_factor*c_parity
    weight=1/sp.sqrt(2)
    return tuple((a*count+b,exchange,
        ((a*count+b,sp.Integer(1)),) if a==b else
        ((a*count+b,weight),(b*count+a,exchange*weight)))
        for a in range(count) for b in range(a,count) if a!=b or exchange==1)


def vertex_binding(elemental,tags):
    from lqcdweave.operators.single_hadron.api import momDict_meson55
    mesons=RecipeVertex(elemental,momentum_dict=momDict_meson55,version='v2')
    def bind(symbol):
        left,right=tags[symbol.tag.tag]
        return mesons(symbol).with_mode_indices((right,left) if symbol.dagger else (left,right))
    return bind


def plan(requests,elemental,light,charm,tags,*,configuration,memory_limit=48<<30,
         host_memory_limit=None,backend='numpy',kernel_batching=True):
    from lqcdweave.contraction.correlator import calculate
    propagators={}
    for flavor,reader in (('u',light),('d',light),('q',light),('c',charm)):
        propagators[f'S^{flavor}']=reader
        propagators[rf'S^{flavor}_\mathrm{{local}}']=reader
    return calculate(requests,vertex_map=vertex_binding(elemental,tags),
        propagator_map=propagators,configuration=configuration,
        time_axes={'sink':1,'source':0},execute=False,optimize='anytime',
        backend=backend,kernel_batching=kernel_batching,storage='bounded',memory_limit=memory_limit,
        host_memory_limit=memory_limit if host_memory_limit is None else host_memory_limit,
        search=dict(root_width=1,branch_width=1,storage_branch_width=1,include_ties=False,component_workers=1))
