"""Actual dilution-vector provenance, independent of production and storage.

An absent document means unknown provenance. Neither array dimensions nor a
flattened mode number establishes a dilution group or a random realization.
"""

from dataclasses import dataclass
from numbers import Integral


DILUTION_SCHEMA = "lqcdweave.dilution-source/v1"
DILUTION_WEIGHT_SCHEME = "component_inclusion-v1"


def _integer(value, name):
    if isinstance(value, bool) or not isinstance(value, Integral) or value < 0:
        raise ValueError(f"{name} must be a nonnegative integer")
    return int(value)


def _identity(value, name):
    if not isinstance(value, str) or not value:
        raise ValueError(f"{name} requires an explicit nonempty actual identity")
    return value


@dataclass(frozen=True)
class DilutionGroup:
    """One ordered parent subspace and its actual retained vector labels.

    ``qr`` is a raw Haar rank-m projector; ``exact`` copies all parents;
    ``u1`` is the legacy unnormalized single phase vector. The covariance
    factor is E[D D†] relative to the parent's projector, not a weight already
    applied to the stored vectors.
    """

    parent_modes: tuple
    vector_labels: tuple
    branch: str = "qr"
    covariance_factor: float | None = None

    def __post_init__(self):
        parents = tuple(_integer(i, "parent mode") for i in self.parent_modes)
        labels = tuple(tuple(_integer(i, "vector label") for i in label)
                       for label in self.vector_labels)
        if not parents or len(set(parents)) != len(parents):
            raise ValueError("dilution parent modes must be nonempty and distinct")
        if not labels or any(len(label) != 2 for label in labels) or len(set(labels)) != len(labels):
            raise ValueError("dilution vector labels must be distinct (block, in_block) pairs")
        n, m = len(parents), len(labels)
        if m > n:
            raise ValueError("dilution group requires m <= n")
        if self.branch not in ("qr", "exact", "u1"):
            raise ValueError("dilution branch must be qr, exact, or u1")
        if self.branch == "exact" and m != n:
            raise ValueError("exact dilution requires all parent modes")
        if self.branch == "u1" and (m != 1 or n <= 1):
            raise ValueError("legacy u1 dilution requires m=1<n")
        factor = m / n if self.branch == "qr" else 1.0
        if self.covariance_factor is not None and float(self.covariance_factor) != factor:
            raise ValueError("raw covariance factor differs from the declared dilution branch")
        object.__setattr__(self, "parent_modes", parents)
        object.__setattr__(self, "vector_labels", labels)
        object.__setattr__(self, "covariance_factor", factor)

    @property
    def n(self):
        return len(self.parent_modes)

    @property
    def m(self):
        return len(self.vector_labels)

    @property
    def first_moment_weight(self):
        return 1.0 / self.covariance_factor

    @property
    def document(self):
        return {"parent_modes": list(self.parent_modes),
                "vector_labels": [list(label) for label in self.vector_labels],
                "n": self.n, "m": self.m, "branch": self.branch,
                "covariance_factor": self.covariance_factor}

    @classmethod
    def from_document(cls, document):
        group = cls(tuple(document["parent_modes"]), tuple(document["vector_labels"]),
                    document["branch"], document["covariance_factor"])
        if document.get("n", group.n) != group.n or document.get("m", group.m) != group.m:
            raise ValueError("dilution group counts differ from its actual labels")
        return group


@dataclass(frozen=True)
class DilutionSource:
    """An actual D dataset with explicit group and time-realization provenance.

    The axis consumes ``ordered_indices``, with a documented mapping to
    ``vector_labels``. Groups are independently generated by the declared
    dilution algorithm. ``time_pools`` maps physical times to actual column
    selection pools. Reusing a pool explicitly declares one shared selection
    across those times; missing pools cannot prove independence.
    """

    data_id: str
    parent_basis_id: str
    groups: tuple
    time_pools: tuple = ()
    algorithm: str = "qr-dilution-v1"

    def __post_init__(self):
        _identity(self.data_id, "data_id")
        _identity(self.parent_basis_id, "parent_basis_id")
        _identity(self.algorithm, "algorithm")
        groups = tuple(self.groups)
        if not groups or any(not isinstance(group, DilutionGroup) for group in groups):
            raise ValueError("dilution source requires explicit DilutionGroup records")
        parents = tuple(i for group in groups for i in group.parent_modes)
        labels = tuple(label for group in groups for label in group.vector_labels)
        if len(set(parents)) != len(parents):
            raise ValueError("dilution parent groups must be disjoint")
        if len(set(labels)) != len(labels):
            raise ValueError("dilution vector labels must be unique across groups")
        pools = tuple((_integer(time, "physical time"),
                       None if pool is None else _identity(pool, "pool_id"))
                      for time, pool in self.time_pools)
        if len({time for time, _ in pools}) != len(pools):
            raise ValueError("dilution time pools must have unique physical times")
        object.__setattr__(self, "groups", groups)
        object.__setattr__(self, "time_pools", pools)

    @property
    def vector_labels(self):
        return tuple(label for group in self.groups for label in group.vector_labels)

    @property
    def ordered_indices(self):
        return tuple(range(len(self.vector_labels)))

    @property
    def first_moment_weights(self):
        return tuple(group.first_moment_weight for group in self.groups
                     for _ in group.vector_labels)

    def group_for_label(self, label):
        label = tuple(label)
        for group in self.groups:
            if label in group.vector_labels:
                return group
        raise ValueError("vector label is absent from the actual dilution source")

    def group_indices(self, group_index):
        group_index = _integer(group_index, "group index")
        if group_index >= len(self.groups):
            raise ValueError("group index exceeds the actual dilution source")
        start = sum(group.m for group in self.groups[:group_index])
        return tuple(range(start, start + self.groups[group_index].m))

    def pool_key(self, time, group_index):
        """Identify a shared column selection independently of physical time.

        Time locates the actual endpoint data. The declared pool identifies
        the random selection, which may be reused at several endpoint times.
        """
        time = _integer(time, "physical time")
        self.group_indices(group_index)
        pool = dict(self.time_pools).get(time)
        if pool is None:
            return None
        return (self.parent_basis_id, pool, self.groups[int(group_index)].parent_modes)

    def pool_id(self, time):
        """Return the explicitly declared physical-time pool, or unknown."""
        return dict(self.time_pools).get(_integer(time, "physical time"))

    def validate_selection(self, indices):
        """Accept explicit flattened labels only when complete groups survive.

        A strict subset changes the saved component selection and requires a
        joint column-inclusion contract when combined with the original; it
        is not silently treated as the original complete rank-m column set.
        """
        indices = tuple(_integer(i, "dilution index") for i in indices)
        if len(set(indices)) != len(indices) or any(i >= len(self.vector_labels) for i in indices):
            raise ValueError("dilution selection requires distinct actual axis indices")
        selected = set(indices)
        for group_index in range(len(self.groups)):
            group = set(self.group_indices(group_index))
            if selected & group and not group <= selected:
                raise ValueError("partial dilution groups require an explicit joint component-inclusion estimator")
        return indices

    @property
    def document(self):
        return {"schema": DILUTION_SCHEMA, "data_id": self.data_id,
                "parent_basis_id": self.parent_basis_id, "algorithm": self.algorithm,
                "groups": [group.document for group in self.groups],
                "vector_labels": [list(label) for label in self.vector_labels],
                "ordered_indices": list(self.ordered_indices),
                "time_pools": [[time, pool] for time, pool in self.time_pools]}

    @classmethod
    def from_document(cls, document):
        if document is None:
            return None
        if document.get("schema") != DILUTION_SCHEMA:
            raise ValueError("unsupported dilution source schema")
        result = cls(document["data_id"], document["parent_basis_id"],
                     tuple(DilutionGroup.from_document(group) for group in document["groups"]),
                     tuple(document.get("time_pools", ())), document["algorithm"])
        if tuple(map(tuple, document.get("vector_labels", result.vector_labels))) != result.vector_labels:
            raise ValueError("dilution flattened vector labels differ from its actual groups")
        if tuple(document.get("ordered_indices", result.ordered_indices)) != result.ordered_indices:
            raise ValueError("dilution ordered indices differ from the actual flattened axis")
        return result

    @classmethod
    def from_description(cls, description, *, data_id, time_pools=None):
        """Bind completed NV provenance to an actual published dataset ID."""
        if not description.get("complete") or description.get("normalization") != "raw":
            raise ValueError("dilution requires completed raw-vector provenance")
        parent_id = description.get("parent_basis_id")
        _identity(parent_id, "parent_basis_id")
        parents, counts = tuple(description["mode_groups"]), tuple(description["vector_counts"])
        branches = tuple(description["branches"])
        factors = tuple(description["covariance_factors"])
        if not (len(parents) == len(counts) == len(branches) == len(factors)):
            raise ValueError("dilution description group fields have different lengths")
        labels = tuple(map(tuple, description["vector_labels"]))
        groups, start = [], 0
        for modes, count, branch, factor in zip(parents, counts, branches, factors):
            count = _integer(count, "vector count")
            groups.append(DilutionGroup(modes, labels[start:start + count], branch, factor))
            start += count
        if start != len(labels):
            raise ValueError("dilution vector counts differ from flattened labels")
        if time_pools is None:
            time_pools = description.get("time_pools", ())
        result = cls(data_id, parent_id, tuple(groups), tuple(time_pools), description["algorithm"])
        if tuple(description["parent_counts"]) != tuple(group.n for group in result.groups):
            raise ValueError("dilution parent counts differ from actual mode groups")
        return result


# Endpoint users may call the same actual source a basis. There is one record
# and one codec, rather than separate provenance systems for production/readers.
DilutionBasis = DilutionSource


__all__ = ["DILUTION_SCHEMA", "DilutionGroup", "DilutionSource", "DilutionBasis"]
