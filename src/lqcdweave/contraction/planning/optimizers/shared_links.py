"""Shared operation definitions and scope-local connection updates.

The original terms are immutable. Scope labels are a compatibility view for
the existing DFS, scorers and fixed-path delivery; costs live in the registry.
An occurrence, rather than a global data identity, is the unit of mutation.
"""
from collections.abc import Sequence


class ScopeLabels(Sequence):
    """One integer label per scope, pointing at an immutable binding record."""

    def __init__(self, records):
        self.definitions = []
        self.ids = {}
        self.labels = [self._intern(record) for record in records]

    def _intern(self, record):
        identity = self.ids.get(record)
        if identity is None:
            identity = len(self.definitions)
            self.ids[record] = identity
            self.definitions.append(record)
        return identity

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, scope):
        if isinstance(scope, slice):
            return [self.definitions[label] for label in self.labels[scope]]
        return self.definitions[self.labels[scope]]

    def __setitem__(self, scope, record):
        self.labels[scope] = self._intern(record)


class SharedLinks:
    """Reverse node index and persistent local descriptions for one branch.

    Recipes and costs survive undo in the registry. Rows below contain only
    recipe references and their occurrence bindings, never copied costs.
    """

    def __init__(self, space):
        self.space = space
        self.by_node = {}
        self.scope_nodes = {}
        self.pending = {}
        self.snapshots = {}
        self.reused_connections = 0
        self.new_connections = 0
        self.scope_updates = 0

    def publish(self, scope, row):
        space = self.space
        before = self.scope_nodes.get(scope, ())
        nodes = set()
        term = space.terms[scope]
        for _, occurrence in row:
            nodes.update(term.factors[p] for p in occurrence.positions + occurrence.cores)
        for node in set(before) - nodes:
            users = self.by_node[node]
            users.discard(scope)
            if not users:
                del self.by_node[node]
        for node in nodes - set(before):
            self.by_node.setdefault(node, set()).add(scope)
        self.scope_nodes[scope] = nodes

    def remember(self, scope, before, after, occurrence):
        """Record the selected connection's local substitution, without IO."""
        space = self.space
        # Layout alternatives are generated by the existing terminal helper.
        # They are not primary connections and must not survive as stale rows.
        row = tuple(item for item in space.rows.get(scope, ())
                    if item[0] not in space.layout_variants)
        self.snapshots[(scope, before)] = row
        consumed = frozenset(occurrence.positions + occurrence.cores)
        keep = tuple(p for p in range(len(before.factors)) if p not in consumed)
        self.pending[scope] = (before, after, keep, row)
        self.scope_updates += 1

    def restore(self, scope, record):
        self.pending.pop(scope, None)

    def row(self, scope, checkpoint):
        """Reuse unaffected links; only describe connections to the new node."""
        space = self.space
        term = space.terms[scope]
        cached = self.snapshots.get((scope, term))
        if cached is not None:
            self.pending.pop(scope, None)
            self.reused_connections += len(cached)
            return cached
        update = self.pending.pop(scope, None)
        if update is None or update[1] != term or space._special_links(scope):
            row = tuple(space._link_row(scope, checkpoint))
            self.new_connections += len(row)
            self.snapshots[(scope, term)] = row
            return row
        _, _, keep, old_row = update
        positions = {old: new for new, old in enumerate(keep)}
        retained = []
        for identity, occurrence in old_row:
            used = occurrence.positions + occurrence.cores
            if all(p in positions for p in used):
                retained.append((identity, occurrence._replace(
                    positions=tuple(positions[p] for p in occurrence.positions),
                    cores=tuple(positions[p] for p in occurrence.cores))))
        # Unchanged endpoints retain their axis relation: an axis needed by
        # either endpoint cannot disappear in a contraction elsewhere.
        added = space._link_row(scope, checkpoint, touching=len(term.factors) - 1)
        self.reused_connections += len(retained)
        self.new_connections += len(added)
        # Preserve the original candidate order for DFS tie-breaking.
        row = tuple(sorted((*retained, *added), key=lambda item: (
            item[1].join is not None,
            item[1].positions if item[1].join is None else (item[1].join,))))
        self.snapshots[(scope, term)] = row
        return row

    def statistics(self):
        return dict(shared_link_reuses=self.reused_connections,
                    shared_link_new_bindings=self.new_connections,
                    shared_link_scope_updates=self.scope_updates)
